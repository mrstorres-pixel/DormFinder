import { test, expect } from '@playwright/test'

test('desktop map stays beside scrolling results and keeps its preview inside the viewport', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const tile = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aGxkAAAAASUVORK5CYII=', 'base64')
  await page.route('https://tile.openstreetmap.org/**', route => route.fulfill({ contentType: 'image/png', body: tile }))
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/listings?q=DEMO')
  const cards = page.locator('.listing-grid .property-card')
  await expect(cards.nth(4)).toBeAttached()
  const column = page.getByRole('complementary', { name: 'Explore listings on the map' })
  const map = page.getByRole('region', { name: 'Listing map', exact: true })
  await expect(map.locator('.campus-marker')).toBeVisible()
  const initial = await column.boundingBox()
  expect(initial.y).toBeLessThan(140)
  expect(initial.y + initial.height).toBeLessThanOrEqual(900)
  expect(initial.x).toBeGreaterThan(650)

  for (const scroll of [700, 1400]) {
    await page.evaluate(y => window.scrollTo(0, y), scroll)
    await expect.poll(async () => Math.round((await column.boundingBox()).y)).toBe(88)
    const box = await column.boundingBox()
    expect(box.y + box.height).toBeLessThanOrEqual(900)
    await expect(map.locator('.leaflet-control-zoom-in')).toBeInViewport()
  }
  await cards.nth(4).getByRole('button', { name: 'Show on map' }).click()
  const preview = page.getByRole('article', { name: 'Selected map listing' })
  await expect(preview).toBeVisible()
  const previewBox = await preview.boundingBox()
  expect(previewBox.y).toBeGreaterThan(88)
  expect(previewBox.y + previewBox.height).toBeLessThan(900)
  await expect(preview.getByLabel('Room in map preview')).toHaveValue(await cards.nth(4).getByRole('combobox').inputValue())
  await preview.getByRole('button', { name: 'Close listing preview' }).click()
  await expect(preview).toHaveCount(0)
  await expect(map).toBeFocused()
  await expect(page.locator('.property-card.is-selected')).toHaveCount(0)
  await map.locator('.price-cluster').first().click()
  await expect.poll(() => page.evaluate(() => JSON.parse(sessionStorage.getItem('dormfinder:browse-context:v1'))?.[0]?.value?.viewport?.zoom || 0)).toBeGreaterThan(15)
  await expect(page.getByRole('button', { name: 'Search this area', exact: true })).toBeVisible()

  // The same layout remains usable on a short laptop screen and after a mobile switch.
  await page.setViewportSize({ width: 1024, height: 600 })
  const shortBox = await column.boundingBox()
  expect(shortBox.y + shortBox.height).toBeLessThanOrEqual(600)
  await page.setViewportSize({ width: 360, height: 800 })
  await page.getByRole('button', { name: 'List only', exact: true }).click()
  await expect(cards.first()).toBeVisible()
  await expect(column).toBeHidden()
  await cards.first().getByRole('button', { name: 'Show on map' }).click()
  await expect(map).toBeVisible()
  await expect(preview).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(errors).toEqual([])
})
