import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { randomUUID } from 'node:crypto'

test('grouped navigation and progressive listing actions keep private drafts and selected room context', async ({ page, baseURL }, testInfo) => {
  test.skip(!process.env.E2E_DEMO_MANIFEST, 'Uses the existing synthetic student and fictional listings.')
  test.setTimeout(120_000)
  const environment = baseURL.startsWith('https:') ? 'cloud' : 'local'
  const accounts = JSON.parse(await readFile(new URL(`../../.secrets/discovery-browser-${environment}-${testInfo.project.name}.json`, import.meta.url), 'utf8'))
  await page.goto('/login')
  await page.getByLabel('Email address').fill(accounts.student.email)
  await page.getByLabel('Password', { exact: true }).fill(accounts.student.password)
  const dashboard = page.waitForResponse(response => new URL(response.url()).pathname.endsWith('/api/v1/favorites') && response.status() === 200)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await dashboard
  const account = page.locator('.account-menu')
  await account.locator('summary').focus()
  await page.keyboard.press('Enter')
  await expect(account).toHaveJSProperty('open', true)
  await expect(account.getByRole('link', { name: 'Profile', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(account).toHaveJSProperty('open', false)
  await expect(account.locator('summary')).toBeFocused()
  await page.locator('.saved-menu > summary').click()
  await page.getByRole('link', { name: /^Shortlists/ }).click()
  await expect(page).toHaveURL(/\/shortlists$/)
  await expect(page.locator('.saved-menu')).toHaveClass(/is-current/)

  const listings = await page.request.get('/api/v1/listings?q=DEMO')
  expect(listings.status()).toBe(200)
  const property = (await listings.json()).data.find(item => item.room_options.length > 1)
  expect(property).toBeTruthy()
  await page.goto('/listings/' + property.id + '?option=' + property.room_options[0].id)
  const room = page.getByLabel('Choose a room option')
  await expect(room).toHaveValue(String(property.room_options[0].id))
  await expect(page.getByLabel('Your question')).toBeHidden()
  await expect(page.getByLabel('Save this room option to')).toBeHidden()
  await expect(page.getByLabel('Preferred viewing time (Philippine time, UTC+8)')).toBeHidden()
  await page.getByText('Ask the owner', { exact: true }).click()
  const draft = 'Synthetic retained visual-flow question ' + randomUUID()
  await page.getByLabel('Your question').fill(draft)
  await page.getByText('Ask the owner', { exact: true }).click()
  await page.getByText('Request a property viewing', { exact: true }).click()
  const viewingNote = page.getByLabel('Viewing note for the owner')
  await viewingNote.fill('Synthetic unsent viewing draft')
  await page.getByText('Request a property viewing', { exact: true }).click()
  page.once('dialog', dialog => dialog.dismiss())
  await room.selectOption(String(property.room_options[1].id))
  await expect(room).toHaveValue(String(property.room_options[0].id))
  await page.getByText('Request a property viewing', { exact: true }).click()
  await expect(viewingNote).toHaveValue('Synthetic unsent viewing draft')
  await page.getByRole('button', { name: 'Discard viewing draft' }).click()
  await page.reload()
  await expect(page.getByLabel('Your question')).toBeVisible()
  await expect(page.getByLabel('Your question')).toHaveValue(draft)
  for (const width of [360, 768, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
  await page.setViewportSize({ width: 360, height: 900 })
  await page.getByRole('button', { name: 'Menu', exact: true }).click()
  await account.locator('summary').click()
  await expect(account.getByRole('link', { name: 'Profile', exact: true })).toBeVisible()
})
