import { test, expect } from '@playwright/test'

test('students keep campus, budget and room context through mobile search and comparison', async ({ page }) => {
  test.setTimeout(120_000)
  const campuses = (await (await page.request.get('/api/v1/campuses')).json()).data
  const ceu = campuses.filter(campus => campus.institution_name === 'Centro Escolar University')
  expect(ceu).toHaveLength(4)
  expect(new Set(ceu.map(campus => campus.id)).size).toBe(4)
  expect(campuses.some(campus => campus.slug === 'tip-quezon-city')).toBe(true)
  const tile = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aGxkAAAAASUVORK5CYII=', 'base64')
  await page.route('https://tile.openstreetmap.org/**', route => route.fulfill({ contentType: 'image/png', body: tile }))
  await page.setViewportSize({ width: 360, height: 900 })
  await page.goto('/')
  const university = page.locator('.home-campus-form').getByRole('combobox', { name: 'College or university' })
  await university.fill('CEU Manila')
  await university.press('Enter')
  await page.getByRole('button', { name: 'Find housing near my campus' }).click()
  const campusId = ceu.find(campus => campus.slug === 'ceu-manila-mendiola').id
  await expect(page).toHaveURL(new RegExp('campus_id=' + campusId + '&radius_km=2&sort=recommended'))
  await page.getByRole('button', { name: /^Filters/ }).click()
  await page.getByLabel('Maximum monthly rent (PHP)').fill('7000')
  await page.getByLabel('Price basis', { exact: true }).selectOption('per_person')
  await page.getByRole('button', { name: 'Close filters', exact: true }).click()
  await page.getByRole('button', { name: /^Filters/ }).click()
  await expect(page.getByLabel('Maximum monthly rent (PHP)')).toHaveValue('7000')
  await expect(page.getByLabel('Price basis', { exact: true })).toHaveValue('per_person')
  const filtered = page.waitForResponse(response => new URL(response.url()).pathname === '/api/v1/listings' && new URL(response.url()).searchParams.get('max_rent_centavos') === '700000' && response.status() === 200)
  await page.getByRole('button', { name: 'Apply filters', exact: true }).click()
  const result = await filtered
  const listing = (await result.json()).data[0]
  expect(listing).toBeTruthy()
  await expect(page).toHaveURL(/max_rent_centavos=700000/)
  const card = page.locator('#listing-card-' + listing.id)
  await expect(card).toBeVisible()
  const title = await card.getByRole('heading').innerText()
  const optionId = await card.getByRole('combobox').inputValue()
  await card.getByRole('checkbox', { name: /Compare/ }).check()
  await page.getByRole('link', { name: 'Compare 1 listing', exact: true }).click()
  const table = page.getByRole('table')
  await expect(table).toBeVisible()
  await table.getByRole('link', { name: title, exact: true }).click()
  await expect(page).toHaveURL(new RegExp('option=' + optionId + '&campus_id=' + campusId))
  await expect(page.getByLabel('Choose a room option')).toHaveValue(optionId)
  const summary = page.getByRole('region', { name: 'Selected room summary' })
  await expect(summary).toBeVisible()
  await expect(summary).toContainText('Known monthly charges')
  await page.getByRole('link', { name: 'Choose a room →' }).click()
  await expect(page).toHaveURL(/#rooms-and-costs$/)
  await page.getByText('Detailed charges and room terms', { exact: true }).click()
  await expect(page.locator('#rooms-and-costs .room-charges').getByText('Known monthly charges', { exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Sign in to ask the owner' })).toHaveAttribute('href', /returnTo=/)
  for (const width of [360, 768, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: '../.local/student-usability-' + test.info().project.name + '-' + width + '.png', fullPage: true })
  }
  await page.getByRole('link', { name: 'DormFinder home' }).click()
  await page.locator('.home-campus-form').getByRole('combobox', { name: 'College or university' }).fill('CEU Malolos')
  await page.locator('.home-campus-form').getByRole('combobox', { name: 'College or university' }).press('Enter')
  await page.getByRole('button', { name: 'Find housing near my campus' }).click()
  await expect(page.getByRole('heading', { name: 'No listings match your search.' })).toBeVisible()
  expect(new URL(page.url()).searchParams.get('radius_km')).toBe('2')
  expect(new URL(page.url()).searchParams.get('campus_id')).toBe(String(ceu.find(campus => campus.slug === 'ceu-malolos').id))
})
