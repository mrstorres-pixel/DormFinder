import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'

test('student and owner calendars read actual private viewing data with Philippine month validation', async ({ browser, baseURL }, testInfo) => {
  test.skip(!process.env.E2E_CAMPUS_DEMO_MANIFEST, 'Uses existing synthetic role accounts.')
  test.setTimeout(120_000)
  const directory = dirname(process.env.E2E_CAMPUS_DEMO_MANIFEST)
  const environment = baseURL.startsWith('https:') ? 'cloud' : 'local'
  const accounts = JSON.parse(await readFile(join(directory, `discovery-browser-${environment}-${testInfo.project.name}.json`), 'utf8'))
  const owner = JSON.parse(await readFile(join(directory, `demo-landlord-${environment}.json`), 'utf8'))
  for (const [role, account] of [['student', accounts.student], ['landlord', owner]]) {
    const context = await browser.newContext({ baseURL })
    try {
      const page = await context.newPage()
      await page.goto('/login')
      await page.getByLabel('Email address').fill(account.email)
      await page.getByLabel('Password', { exact: true }).fill(account.password)
      await page.getByRole('button', { name: 'Sign in', exact: true }).click()
      await expect(page).toHaveURL(role === 'student' ? /\/account$/ : /\/landlord$/)
      await page.goto('/viewings?mode=calendar&month=2026-10')
      const calendar = page.getByRole('region', { name: 'Viewing calendar' })
      await expect(calendar).toBeVisible()
      await expect(calendar).toHaveAttribute('aria-busy', 'false')
      const data = await page.evaluate(async () => {
        const valid = await fetch('/api/v1/viewings?month=2026-10')
        const invalid = await fetch('/api/v1/viewings?month=2026-13')
        return { status: valid.status, invalid: invalid.status, body: await valid.json() }
      })
      expect(data.status).toBe(200)
      expect(data.invalid).toBe(422)
      for (const row of data.body.data) expect(new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Manila', year: 'numeric', month: '2-digit' }).format(new Date(row.starts_at))).toBe('2026-10')
      await page.setViewportSize({ width: 390, height: 844 })
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      await page.screenshot({ path: `../.local/calendar-live-${role}-${testInfo.project.name}.png`, fullPage: true })
    } finally { await context.close() }
  }
})

test('campus catalog covers every campus with three street-based listings, working images and selected-room journeys', async ({ page }, testInfo) => {
  test.skip(!process.env.E2E_CAMPUS_DEMO_MANIFEST, 'Run against the explicitly replaced demo catalog.')
  test.setTimeout(180_000)
  const manifest = JSON.parse(await readFile(process.env.E2E_CAMPUS_DEMO_MANIFEST, 'utf8'))
  expect(manifest.version).toBe(2)
  expect(manifest.ids).toHaveLength(45)
  const campuses = await (await page.request.get('/api/v1/campuses')).json()
  expect(campuses.data).toHaveLength(15)
  const mapResponse = await page.request.get('/api/v1/listings-map?q=DEMO')
  expect(mapResponse.ok()).toBe(true)
  const mapped = await mapResponse.json()
  expect(mapped.meta.total).toBe(45)
  expect(mapped.data.every(row => !Object.hasOwn(row, 'distance_from_campus'))).toBe(true)
  const unselectedDetail = await (await page.request.get('/api/v1/listings/' + mapped.data[0].id)).json()
  expect(unselectedDetail.data).not.toHaveProperty('distance_from_campus')
  expect(new Set(mapped.data.map(row => row.latitude + ',' + row.longitude)).size).toBe(45)
  for (const campus of campuses.data) {
    const entries = manifest.catalog.filter(row => row.campus_slug === campus.slug)
    expect(entries).toHaveLength(3)
    const response = await page.request.get('/api/v1/listings-map?campus_id=' + campus.id + '&radius_km=2&sort=recommended')
    expect(response.ok()).toBe(true)
    const nearby = (await response.json()).data
    for (const entry of entries) {
      const listing = nearby.find(row => row.title === entry.title)
      expect(listing, entry.key).toBeTruthy()
      expect(listing.latitude).toBe(entry.latitude)
      expect(listing.longitude).toBe(entry.longitude)
      expect(listing.room_options).toHaveLength(2)
      expect(listing.room_options[0].capacity).toBe(entry.capacity)
      expect(listing.photos).toHaveLength(1)
      expect(listing.photos[0].caption).toContain('AI-generated demo interior')
      const image = await page.request.get(listing.photos[0].url)
      expect(image.ok(), entry.key + ' image').toBe(true)
      expect(image.headers()['content-type']).toContain('image/jpeg')
      expect((await image.body()).length).toBeGreaterThan(20_000)
    }
  }
  for (const id of manifest.archived) expect((await page.request.get('/api/v1/listings/' + id)).status()).toBe(404)
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/listings?q=DEMO')
  const unselectedMap = page.getByRole('region', { name: 'Listing map', exact: true })
  await expect(unselectedMap.locator('.leaflet-marker-icon').first()).toBeVisible()
  await expect(unselectedMap.locator('.campus-marker')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Back to campus', exact: true })).toHaveCount(0)
  const unselectedCards = page.locator('.property-card')
  await unselectedCards.nth(0).getByRole('checkbox', { name: /Compare/ }).check()
  await unselectedCards.nth(1).getByRole('checkbox', { name: /Compare/ }).check()
  const tray = page.getByRole('region', { name: 'Your comparison selection' })
  await expect(tray).toBeInViewport()
  await page.screenshot({ path: `../.local/unselected-browse-live-${testInfo.project.name}.png` })
  await tray.getByRole('link', { name: 'Compare 2 listings' }).click()
  const comparedRooms = page.getByRole('table').first().getByRole('combobox')
  await expect(comparedRooms).toHaveCount(2)
  expect(Math.abs((await comparedRooms.nth(0).boundingBox()).y - (await comparedRooms.nth(1).boundingBox()).y)).toBeLessThan(1)
  await expect(page.getByRole('rowheader', { name: 'Campus distance', exact: true })).toHaveCount(0)
  await page.screenshot({ path: `../.local/unselected-comparison-live-${testInfo.project.name}.png`, fullPage: true })
  const campus = campuses.data.find(row => row.slug === 'pup-mabini')
  await page.goto('/listings?campus_id=' + campus.id + '&radius_km=1&sort=recommended')
  const card = page.locator('.property-card').first()
  await expect(card.locator('img').first()).toBeVisible()
  await expect.poll(() => card.locator('img').first().evaluate(image => image.complete && image.naturalWidth > 500)).toBe(true)
  for (const image of await page.locator('.property-card img').all()) {
    await image.scrollIntoViewIfNeeded()
    await expect.poll(() => image.evaluate(image => image.complete && image.naturalWidth > 500)).toBe(true)
  }
  await page.evaluate(() => scrollTo(0, 0))
  await page.screenshot({ path: `../.local/campus-catalog-${testInfo.project.name}-desktop.png`, fullPage: true })
  await card.locator('a:has(img)').first().click()
  await expect(page).toHaveURL(/\/listings\/\d+/)
  const gallery = page.getByRole('region', { name: 'Property photo gallery' })
  await expect.poll(() => gallery.locator('figure img').evaluate(image => image.complete && image.naturalWidth > 500)).toBe(true)
  await gallery.getByRole('button', { name: /enlarge|open.*photo/i }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  const option = page.getByRole('group', { name: 'Choose a room option' })
  await option.locator('label').last().click()
  await page.getByRole('button', { name: '+ Compare', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: `../.local/campus-listing-${testInfo.project.name}-mobile.png`, fullPage: true })
  expect(errors).toEqual([])
})
