import { test, expect } from '@playwright/test'

const campuses = [{ id: 8, name: 'TIP Manila — P. Casal', slug: 'tip-manila-casal', latitude: 14.5953, longitude: 120.9881 }, { id: 9, name: 'DLSU Manila', slug: 'dlsu-manila', latitude: 14.5646, longitude: 120.993 }]
const room = { id: 11, name: 'Twin beds', capacity: 2, inventory_type: 'bedspace', price_basis: 'per_person', monthly_rent_centavos: 400000, monthly_fixed_total_centavos: 400000, move_in_fixed_total_centavos: 800000, deposit_centavos: 400000, advance_months: 1, available_units: 1, total_units: 2, availability_stale: false, fees: [] }
const places = ['A long residence name that wraps across several lines near the university', 'Short name', 'Another residence'].map((title, i) => ({ id: i + 1, title, city: 'Manila', property_type: 'dormitory', description: 'A fictional property used for testing the connected browse journey.', address: 'Test street', latitude: 14.59 + i * .02, longitude: 120.98 + i * .015, photos: [{ id: i + 1, url: '/images/demo/twin-room.webp', caption: 'Fictional room image' }], room_options: [{ ...room, id: 11 + i * 10 }, { ...room, id: 12 + i * 10, name: 'Other twin room' }] }))

async function fixture(page, signedIn = false) {
  await page.route('https://tile.openstreetmap.org/**', route => route.fulfill({ status: 204 }))
  await page.route('**/sanctum/csrf-cookie', route => route.fulfill({ status: 204 }))
  await page.route('**/api/v1/**', route => {
    const url = new URL(route.request().url()), path = url.pathname
    const json = data => route.fulfill({ json: { data, meta: { total: places.length, current_page: 1, last_page: 1 } } })
    if (path.endsWith('/me')) return signedIn ? json({ id: 50, name: 'Test student', role: 'student' }) : route.fulfill({ status: 401, json: { message: 'Unauthenticated' } })
    if (path.endsWith('/campuses')) return json(campuses)
    if (path.endsWith('/count')) return json({ unread: 0 })
    if (path.includes('saved-places') || path.endsWith('/viewings')) return json([])
    const annotate = p => ({ ...p, distance_from_campus: { campus_id: Number(url.searchParams.get('campus_id') || 8), meters: p.id * 200 } })
    if (path.endsWith('/compare')) return json(route.request().postDataJSON().selections.map(selection => {
      const property = annotate(places.find(p => p.id === selection.property_id))
      return { ...property, alternative_room_options: property.room_options, room_options: property.room_options.filter(room => room.id === selection.room_option_id) }
    }))
    const id = path.match(/\/listings\/(\d+)$/)?.[1]
    return json(id ? annotate(places.find(p => p.id === Number(id))) : places.map(annotate))
  })
}

test('unselected browsing has no campus reference and clearing an explicit campus returns to neutral results', async ({ page }) => {
  await fixture(page)
  await page.setViewportSize({ width: 1440, height: 950 })
  await page.goto('/listings')
  const map = page.getByRole('region', { name: 'Listing map', exact: true })
  await expect(map.locator('.leaflet-marker-icon').first()).toBeVisible()
  await expect(map.locator('.campus-marker')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Back to campus', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Show results', exact: true })).toBeVisible()
  await page.locator('.property-card').first().getByRole('button', { name: 'Show on map' }).click()
  const preview = page.getByRole('article', { name: 'Selected map listing' })
  await expect(preview).toBeVisible()
  await expect(preview.getByRole('link', { name: 'View listing' })).toHaveAttribute('href', '/listings/1?option=11')
  await expect(page.getByRole('button', { name: 'Walk to campus', exact: true })).toHaveCount(0)
  await preview.getByRole('button', { name: 'Close listing preview' }).click()
  await expect(page.locator('.card-location').first()).toHaveText('Manila')
  await expect(page.getByRole('option', { name: 'Nearest campus first' })).toHaveJSProperty('disabled', true)
  await expect(page.getByRole('option', { name: 'Recommended near campus' })).toHaveJSProperty('disabled', true)
  const campus = page.getByRole('combobox', { name: 'College or university' })
  await campus.fill('DLSU')
  await campus.press('Enter')
  await page.getByRole('button', { name: 'Search campus' }).click()
  await expect(map.locator('.campus-marker')).toHaveAttribute('title', /DLSU/)
  await expect(page.getByRole('button', { name: 'Back to campus' })).toBeVisible()
  await expect(page.getByRole('option', { name: 'Recommended near campus' })).toHaveJSProperty('disabled', false)
  await page.getByRole('button', { name: 'Clear selected campus' }).click()
  await page.getByRole('button', { name: 'Search campus' }).click()
  await expect(map.locator('.leaflet-marker-icon').first()).toBeVisible()
  await expect(map.locator('.campus-marker')).toHaveCount(0)
  await expect(page.locator('.card-location').first()).toHaveText('Manila')
})

test('room selectors align and the floating comparison action follows scroll, selected rooms and mobile navigation', async ({ page }, testInfo) => {
  await fixture(page, true)
  await page.setViewportSize({ width: 1440, height: 950 })
  await page.goto('/listings')
  const cards = page.locator('.property-card')
  await expect(cards).toHaveCount(3)
  const first = cards.nth(0).getByRole('combobox'), second = cards.nth(1).getByRole('combobox')
  expect(Math.abs((await first.boundingBox()).y - (await second.boundingBox()).y)).toBeLessThan(1)
  await first.selectOption('12')
  await cards.nth(0).getByRole('checkbox').check()
  await cards.nth(1).getByRole('checkbox').check()
  const tray = page.getByRole('region', { name: 'Your comparison selection' })
  await expect(tray.getByRole('link', { name: 'Compare 2 listings' })).toHaveAttribute('href', '/compare?items=1:12,2:21')
  await page.evaluate(() => scrollTo(0, document.body.scrollHeight))
  await expect(tray).toBeInViewport()
  expect((await tray.boundingBox()).y).toBeGreaterThan(780)
  await page.screenshot({ path: `../.local/browse-tray-${testInfo.project.name}-desktop.png`, fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  const tabs = page.getByRole('navigation', { name: 'Mobile navigation' })
  await expect(tray).toBeInViewport()
  expect((await tray.boundingBox()).y + (await tray.boundingBox()).height).toBeLessThanOrEqual((await tabs.boundingBox()).y)
  await tray.getByRole('link', { name: 'Compare 2 listings' }).click()
  const selectors = page.getByRole('table').first().getByRole('combobox')
  await expect(selectors).toHaveCount(2)
  expect(Math.abs((await selectors.nth(0).boundingBox()).y - (await selectors.nth(1).boundingBox()).y)).toBeLessThan(1)
  await expect(page.getByRole('rowheader', { name: 'Campus distance', exact: true })).toHaveCount(0)
  await page.screenshot({ path: `../.local/comparison-alignment-${testInfo.project.name}.png`, fullPage: true })
  await page.getByRole('link', { name: 'Choose listings' }).click()
  await expect(tray).toBeVisible()
  await page.getByRole('button', { name: 'List only', exact: true }).click()
  await page.locator('.property-card').first().getByRole('link', { name: 'Open listing: ' + places[0].title }).click()
  const visit = page.locator('.listing-mobile-action')
  await expect(visit).toBeVisible()
  expect((await tray.boundingBox()).y + (await tray.boundingBox()).height).toBeLessThanOrEqual((await visit.boundingBox()).y)
  await tray.getByRole('button', { name: 'Clear selection' }).click()
  await expect(tray).toHaveCount(0)
})
