import { test, expect } from '@playwright/test'

test('real comparison calculates both walks to CEU and switches the highlighted route', async ({ page }, testInfo) => {
  test.setTimeout(180_000)
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const directory = await page.request.get('/api/v1/campuses')
  expect(directory.ok()).toBe(true)
  const campus = (await directory.json()).data.find(campus => /CEU/.test(campus.name) && /Mendiola/.test(campus.name))
  expect(campus).toBeTruthy()
  const result = await page.request.get('/api/v1/listings', { params: { campus_id: campus.id, radius_km: 2, sort: 'distance', q: 'DEMO' } })
  expect(result.ok()).toBe(true)
  const listings = (await result.json()).data.filter(listing => listing.latitude != null && listing.longitude != null && listing.room_options.length).slice(0, 2)
  expect(listings).toHaveLength(2)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/compare?items=' + listings.map(listing => listing.id + ':' + listing.room_options[0].id).join(','))
  const destination = page.getByRole('combobox', { name: 'Walking destination', exact: true })
  await expect(destination).toHaveValue('')
  await destination.fill(campus.name)
  await page.getByRole('option').first().click()
  const walk = page.getByRole('row', { name: /Walk to campus/ })
  await expect(walk.getByRole('button', { name: /Show walking route from/ })).toHaveCount(2, { timeout: 90_000 })
  await expect(walk).not.toContainText('straight-line')
  const map = page.getByRole('region', { name: 'Listing map', exact: true })
  await expect(map.locator('.walking-route-path')).toHaveCount(1)
  await walk.getByRole('button', { name: 'Show walking route from ' + listings[1].title, exact: true }).click()
  await expect(page.locator('.comparison-route-summary')).toContainText(listings[1].title + ' to ' + campus.name)
  await page.screenshot({ path: `../.local/comparison-real-${testInfo.project.name}-desktop.png`, fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Clear selected campus' }).click()
  await expect(walk).toContainText('Choose a campus above')
  await expect(map.locator('.walking-route-path')).toHaveCount(0)
  expect(errors).toEqual([])
})
