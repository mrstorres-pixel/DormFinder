import { test, expect } from '@playwright/test'

test('filter drawer preserves layout and drafts, then applies refinements without losing the map', async ({ page }) => {
  test.setTimeout(120_000)
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const tile = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aGxkAAAAASUVORK5CYII=', 'base64')
  await page.route('https://tile.openstreetmap.org/**', route => route.fulfill({ contentType: 'image/png', body: tile }))
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/listings?q=DEMO')
  const card = page.locator('.listing-grid .property-card').first()
  await expect(card).toBeVisible({ timeout: 30_000 })
  const map = page.getByRole('region', { name: 'Listing map', exact: true })
  await expect(map.locator('.campus-marker')).toBeVisible()
  await map.focus()
  await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('button', { name: 'Search this area', exact: true })).toBeVisible()
  const readView = () => page.evaluate(() => JSON.parse(sessionStorage.getItem('dormfinder:browse-context:v1'))[0].value.viewport)
  const before = await readView()
  const cardBox = await card.boundingBox()
  const mapBox = await map.boundingBox()
  const sort = page.getByLabel('Sort listings')
  await expect(sort.locator('option[value=rent_asc]')).toHaveJSProperty('disabled', true)
  const trigger = page.getByRole('button', { name: /^Filters/ })
  await trigger.click()
  const drawer = page.getByRole('dialog', { name: 'Find your fit' })
  await expect(drawer).toBeVisible()
  await expect.poll(async () => Math.round((await card.boundingBox()).y)).toBe(Math.round(cardBox.y))
  expect(Math.abs((await map.boundingBox()).x - mapBox.x)).toBeLessThan(2)
  const backgroundScroll = await page.evaluate(() => scrollY)
  await page.mouse.move(1100, 400)
  await page.mouse.wheel(0, 500)
  expect(await page.evaluate(() => scrollY)).toBe(backgroundScroll)
  await drawer.getByRole('button', { name: 'Close filters' }).focus()
  await page.keyboard.press('Shift+Tab')
  await expect(drawer.getByRole('button', { name: 'Apply filters' })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(drawer.getByRole('button', { name: 'Close filters' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(drawer).toBeHidden()
  await expect(trigger).toBeFocused()
  await trigger.click()
  await drawer.getByLabel('Maximum monthly rent (PHP)').fill('9000')
  await drawer.getByLabel('Price basis', { exact: true }).selectOption('per_person')
  await page.mouse.click(1000, 350)
  await expect(drawer).toBeHidden()
  expect(new URL(page.url()).searchParams.has('max_rent_centavos')).toBe(false)
  await expect(trigger).toBeFocused()
  await trigger.click()
  await expect(drawer.getByLabel('Maximum monthly rent (PHP)')).toHaveValue('9000')
  await expect(drawer.getByLabel('Price basis', { exact: true })).toHaveValue('per_person')
  await drawer.getByRole('button', { name: 'Apply filters' }).click()
  await expect(drawer).toBeHidden()
  await expect(page).toHaveURL(/max_rent_centavos=900000/)
  await expect(trigger).toHaveText('Filters3')
  await expect(map.locator('.campus-marker')).toBeVisible()
  await expect.poll(readView).toEqual(before)
  await sort.selectOption('rent_asc')
  await expect(page).toHaveURL(/sort=rent_asc/)
  await expect(map.locator('.campus-marker')).toBeVisible()
  await expect.poll(readView).toEqual(before)
  await trigger.click()
  await drawer.getByRole('button', { name: 'Clear all', exact: true }).click()
  await expect(drawer.getByLabel('Maximum monthly rent (PHP)')).toHaveValue('')
  await expect(page).toHaveURL(/max_rent_centavos=900000/)
  await drawer.getByRole('button', { name: 'Close filters' }).click()
  await trigger.click()
  await expect(drawer.getByLabel('Maximum monthly rent (PHP)')).toHaveValue('')
  await drawer.getByRole('button', { name: 'Apply filters' }).click()
  await expect(page).toHaveURL(/\/listings\?sort=newest$/)

  await page.setViewportSize({ width: 360, height: 800 })
  await trigger.click()
  await expect(drawer).toBeVisible()
  await expect(drawer.getByRole('button', { name: 'Apply filters' })).toBeInViewport()
  await drawer.locator('.filter-drawer-body').evaluate(element => { element.scrollTop = element.scrollHeight })
  await expect(drawer.getByLabel('Available units confirmed within 14 days')).toBeInViewport()
  await expect(drawer.getByRole('button', { name: 'Close filters' })).toBeInViewport()
  await expect(drawer.getByRole('button', { name: 'Apply filters' })).toBeInViewport()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await drawer.getByRole('button', { name: 'Close filters' }).click()
  expect(await page.evaluate(() => document.documentElement.style.overflow)).toBe('')
  expect(errors).toEqual([])
})
