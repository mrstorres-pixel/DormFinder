import { test, expect } from '@playwright/test'
import { pesos } from '../src/lib/money.js'
test('map preview room changes update the listing card, price marker and comparison together', async ({ page }) => {
  const tile = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aGxkAAAAASUVORK5CYII=','base64')
  await page.route('https://tile.openstreetmap.org/**',route => route.fulfill({ contentType:'image/png',body:tile }))
  const listings = page.waitForResponse(response => new URL(response.url()).pathname.endsWith('/api/v1/listings') && response.request().method() === 'GET')
  await page.goto('/listings?q=DEMO')
  const response = await listings
  expect(response.status()).toBe(200)
  await response.finished()
  const properties = (await response.json()).data
  const card = page.locator('.listing-grid .property-card').first()
  await expect(card).toBeVisible()
  const select = card.getByRole('combobox')
  const first = await select.locator('option').first().getAttribute('value')
  const last = await select.locator('option').last().getAttribute('value')
  expect(first).not.toBe(last)
  await select.selectOption(last)
  await card.getByRole('checkbox',{name:/Compare/}).check()
  await page.locator('.property-card').nth(1).getByRole('checkbox',{name:/Compare/}).check()
  await card.getByRole('button',{name:'Show on map'}).click()
  const preview = page.getByRole('article',{name:'Selected map listing'})
  await preview.getByRole('button', { name: 'Room details' }).click()
  await expect(preview.getByLabel('Room in map preview')).toHaveValue(last)
  await preview.getByLabel('Room in map preview').selectOption(first)
  await expect(select).toHaveValue(first)
  const comparison = page.getByRole('region',{name:'Your comparison selection'}).getByRole('link')
  await expect(comparison).toHaveAttribute('href',new RegExp('items=\\d+:' + first + ','))
  const price = (await card.locator('.room-price').innerText()).split(' ')[0]
  const selectedRoom = properties[0].room_options.find(room => String(room.id) === first)
  const monthly = pesos(selectedRoom.monthly_fixed_total_centavos)
  await expect(preview).toContainText(monthly + ' known monthly')
  await expect(page.locator('.price-marker.is-selected')).toContainText(price)
  await comparison.click()
  await expect(page.getByRole('region',{name:'Comparison highlights'})).toBeVisible()
  await expect(page.getByRole('table').getByRole('combobox').first()).toHaveValue(first)
  await expect(page.getByRole('row').filter({ has: page.getByRole('rowheader', { name: 'Monthly base rent', exact: true }) })).toContainText(price)
  await expect(page.getByRole('row').filter({ has: page.getByRole('rowheader', { name: 'Known monthly charges', exact: true }) }).locator('td').first()).toHaveText(monthly)
})
