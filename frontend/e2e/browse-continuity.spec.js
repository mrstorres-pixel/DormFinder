import { test, expect } from '@playwright/test'

test('listing round trips restore unsubmitted map movement, room choice and display mode', async ({ page }) => {
  test.setTimeout(120_000)
  const tile = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aGxkAAAAASUVORK5CYII=', 'base64')
  await page.route('https://tile.openstreetmap.org/**', route => route.fulfill({ contentType: 'image/png', body: tile }))
  const campuses = (await (await page.request.get('/api/v1/campuses')).json()).data
  const campus = campuses.find(item => item.slug === 'tip-manila-casal')
  await page.goto('/listings?q=DEMO&campus_id=' + campus.id)
  const card = page.locator('.listing-grid .property-card').first()
  await expect(card).toBeVisible({ timeout: 90_000 })
  const option = card.getByRole('combobox')
  const alternative = await option.locator('option').last().getAttribute('value')
  await option.selectOption(alternative)
  const title = await card.getByRole('heading').innerText()
  await card.getByRole('button', { name: 'Show on map' }).click()
  const map = page.getByRole('region', { name: 'Listing map', exact: true })
  await expect(map.locator('.campus-marker')).toBeVisible()
  await map.locator('.leaflet-control-zoom-out').click()
  await expect.poll(() => page.evaluate(() => JSON.parse(sessionStorage.getItem('dormfinder:browse-context:v1'))?.[0]?.value?.viewport?.zoom)).toBe(14)
  const beforePan = await page.evaluate(() => JSON.stringify(JSON.parse(sessionStorage.getItem('dormfinder:browse-context:v1'))[0].value.viewport.center))
  await map.scrollIntoViewIfNeeded()
  await map.focus()
  await page.keyboard.press('ArrowRight')
  await expect.poll(() => page.evaluate(() => JSON.parse(sessionStorage.getItem('dormfinder:browse-context:v1'))?.[0]?.value?.viewport?.needsSearch)).toBe(true)
  await expect.poll(() => page.evaluate(() => JSON.stringify(JSON.parse(sessionStorage.getItem('dormfinder:browse-context:v1'))[0].value.viewport.center))).not.toBe(beforePan)
  const saved = await page.evaluate(() => JSON.parse(sessionStorage.getItem('dormfinder:browse-context:v1'))[0].value)
  const markerPosition = () => map.locator('.campus-marker').evaluate(marker => { const box = marker.getBoundingClientRect(); const map = marker.closest('.leaflet-container').getBoundingClientRect(); return [Math.round(box.x - map.x), Math.round(box.y - map.y)] })
  const position = await markerPosition()
  const originalUrl = page.url()
  await card.getByRole('link', { name: title, exact: true }).click()
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
  await page.goBack()
  await expect(page).toHaveURL(originalUrl)
  await expect(page.getByRole('article', { name: 'Selected map listing' })).toContainText(title)
  await expect(page.locator('.property-card.is-selected').getByRole('combobox')).toHaveValue(alternative)
  await expect.poll(markerPosition).toEqual(position)
  await expect(page.getByRole('button', { name: 'Search this area', exact: true })).toBeVisible()
  expect(new URL(page.url()).searchParams.has('south')).toBe(false)
  await expect.poll(() => page.evaluate(() => JSON.parse(sessionStorage.getItem('dormfinder:browse-context:v1'))[0].value.viewport.zoom)).toBe(saved.viewport.zoom)

  await page.getByRole('button', { name: 'List only', exact: true }).click()
  await page.locator('.property-card.is-selected').getByRole('link', { name: title, exact: true }).click()
  await page.getByRole('link', { name: /Browse listings/ }).click()
  await expect(page.getByRole('heading', { name: 'Places for your student life', exact: true })).toBeVisible()
  await expect(map).toBeHidden()
  await expect(page.getByRole('button', { name: 'Show map', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Show map', exact: true }).click()
  await expect.poll(markerPosition).toEqual(position)

  await page.getByRole('combobox', { name: 'College or university' }).fill('DLSU')
  await page.getByRole('button', { name: /DLSU/ }).click()
  await page.getByRole('button', { name: 'Search campus', exact: true }).click()
  await expect(map.locator('.campus-marker')).toHaveAttribute('title', /DLSU/)
  await expect(map.locator('.leaflet-tile').first()).toHaveAttribute('src', /\/15\//)
  await expect(page.getByRole('article', { name: 'Selected map listing' })).toHaveCount(0)
})

