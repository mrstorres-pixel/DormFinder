import { test, expect } from '@playwright/test'

test('visible campus search and the separate drawer retain requirements without retaining the old area', async ({ page }) => {
  const keyWarnings = []
  page.on('console', message => { if (message.type() === 'error' && /Encountered two children|unique.*key/.test(message.text())) keyWarnings.push(message.text()) })
  test.setTimeout(120_000)
  const directory = (await (await page.request.get('/api/v1/campuses')).json()).data
  const first = directory.find(campus => campus.slug === 'ue-manila')
  const next = directory.find(campus => campus.slug === 'dlsu-manila')
  expect(first).toBeTruthy(); expect(next).toBeTruthy()
  const tile = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aGxkAAAAASUVORK5CYII=', 'base64')
  await page.route('https://tile.openstreetmap.org/**', route => route.fulfill({ contentType: 'image/png', body: tile }))
  await page.setViewportSize({ width: 1440, height: 900 })
  const params = new URLSearchParams({ campus_id: first.id, radius_km: '2', price_basis: 'per_person', max_rent_centavos: '900000', 'amenities[]': 'wifi', page: '2', south: '14.55', north: '14.65', west: '120.95', east: '121.05' })
  await page.goto('/listings?' + params)
  const form = page.getByRole('form', { name: 'Search places' })
  const campus = form.getByRole('combobox', { name: 'Campus, location or listing' })
  await expect(campus).toHaveValue(first.name)
  await expect(page.getByText('Choose a price basis in Filters to sort by rent.', { exact: true })).toHaveCount(0)
  await expect(page.locator('.discovery-information')).toHaveCount(0)
  const toggle = page.getByRole('button', { name: /^Filters/ })
  await toggle.click()
  const drawer = page.getByRole('dialog', { name: 'Find your fit' })
  await expect(drawer.getByRole('combobox', { name: 'Campus, location or listing' })).toHaveCount(0)
  await drawer.getByRole('button', { name: 'Clear filters', exact: true }).click()
  expect(new URL(page.url()).searchParams.get('max_rent_centavos')).toBe('900000')
  await drawer.getByRole('button', { name: 'Apply filters', exact: true }).click()
  await expect(campus).toHaveValue(first.name)
  await expect.poll(() => new URL(page.url()).searchParams.get('max_rent_centavos')).toBeNull()
  expect(new URL(page.url()).searchParams.get('campus_id')).toBe(String(first.id))
  expect(new URL(page.url()).searchParams.has('south')).toBe(false)
  await expect(toggle).toHaveText('Filters')
  await toggle.click()
  await drawer.getByLabel('Price basis', { exact: true }).selectOption('per_person')
  await drawer.getByLabel('Maximum monthly rent (PHP)').fill('9000')
  await drawer.getByLabel('Wi-Fi', { exact: true }).check()
  await drawer.getByRole('button', { name: 'Apply filters' }).click()
  await expect(toggle).toHaveText('Filters3')
  await campus.fill('DLSU Manila')
  await form.getByRole('button', { name: /^Campus .*DLSU/ }).click()
  await form.getByRole('button', { name: 'Search places', exact: true }).click()
  await expect.poll(() => new URL(page.url()).searchParams.get('campus_id')).toBe(String(next.id))
  await expect(page.locator('.discovery-controls .eyebrow')).toHaveText(next.name)
  await expect(campus).toHaveValue(next.name)
  const applied = new URL(page.url()).searchParams
  expect(applied.get('max_rent_centavos')).toBe('900000')
  expect(applied.getAll('amenities[]')).toEqual(['wifi'])
  expect(applied.get('radius_km')).toBe('2')
  expect(applied.has('page')).toBe(false)
  expect(applied.has('south')).toBe(false)
  await form.getByRole('button', { name: 'Clear search' }).click()
  await form.getByRole('button', { name: 'Search places', exact: true }).click()
  await expect.poll(() => new URL(page.url()).searchParams.get('campus_id')).toBeNull()
  await expect(page.locator('.discovery-controls .eyebrow')).toHaveText('FIND YOUR CAMPUS. FIND YOUR PLACE.')
  expect(new URL(page.url()).searchParams.has('radius_km')).toBe(false)
  expect(new URL(page.url()).searchParams.get('max_rent_centavos')).toBe('900000')
  await campus.fill('Unlisted University')
  await form.getByRole('button', { name: 'Search places', exact: true }).click()
  await expect.poll(() => new URL(page.url()).searchParams.get('q')).toBe('Unlisted University')
  await expect(campus).toHaveValue('Unlisted University')
  expect(new URL(page.url()).searchParams.has('campus_id')).toBe(false)
  for (const width of [360, 768]) {
    await page.setViewportSize({ width, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
  expect(keyWarnings).toEqual([])
})
